import { Schema } from 'effect'
import { readFile } from 'node:fs/promises'
import { join } from 'node:path'
import type { Plugin } from 'vite'

import type { Model } from './models.ts'

// NOTICES.md: every dependency the app ships, read from the lockfile (the
// packages a production install keeps), and every model's files, read
// from models.json.

const LockedPackage = Schema.Struct({
  version: Schema.optional(Schema.String),
  license: Schema.optional(Schema.String),
  dev: Schema.optional(Schema.Boolean),
  link: Schema.optional(Schema.Boolean),
})

export const Lockfile = Schema.Struct({
  packages: Schema.Record(Schema.String, LockedPackage),
})
export type Lockfile = typeof Lockfile.Type

export type ShippedPackage = Readonly<{
  name: string
  version: string
  licence: string
}>

const packageName = (path: string): string =>
  path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length)

// The packages a production install keeps: every locked package that is
// not marked dev-only, the project itself aside.
export const shippedPackages = (
  lockfile: Lockfile,
): ReadonlyArray<ShippedPackage> =>
  Object.entries(lockfile.packages)
    .filter(([path, locked]) => path !== '' && locked.dev !== true)
    .map(([path, locked]) => {
      if (locked.version === undefined || locked.license === undefined) {
        throw new Error(
          `package-lock.json gives ${path} no version or licence: NOTICES.md cannot name it`,
        )
      }
      return {
        name: packageName(path),
        version: locked.version,
        licence: locked.license,
      }
    })
    .toSorted(
      (a, b) =>
        a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
    )

const row = (cells: ReadonlyArray<string>): string =>
  `| ${cells.map(cell => cell.replaceAll('|', '\\|')).join(' | ')} |`

export const notices = (
  lockfile: Lockfile,
  models: ReadonlyArray<Model>,
): string =>
  [
    '<!-- Generated by `npm run generate` from package-lock.json and models.json. Do not edit. -->',
    '',
    '# Notices',
    '',
    "Intone's own code is all rights reserved (see `LICENSE`).",
    'The app ships these third-party packages and model files, each under its own licence.',
    '',
    '## Packages',
    '',
    row(['Package', 'Version', 'Licence']),
    row(['-', '-', '-']),
    ...shippedPackages(lockfile).map(({ name, version, licence }) =>
      row([name, version, licence]),
    ),
    '',
    '## Models',
    '',
    row(['Model', 'Files', 'Licence', 'Source']),
    row(['-', '-', '-', '-']),
    ...models.map(model =>
      row([
        model.name,
        model.files.map(file => `${model.id}/${file.path}`).join(', '),
        model.licence,
        model.source,
      ]),
    ),
    '',
  ].join('\n')

// The production build carries NOTICES.md beside the app, at /NOTICES.md,
// so every copy of the app names the packages and model files it ships
// and their licences.
export const noticesFile = (): Plugin => {
  let root = process.cwd()
  return {
    name: 'intone:notices',
    apply: 'build',
    configResolved(config) {
      root = config.root
    },
    async generateBundle() {
      this.emitFile({
        type: 'asset',
        fileName: 'NOTICES.md',
        source: await readFile(join(root, 'NOTICES.md'), 'utf8'),
      })
    },
  }
}
